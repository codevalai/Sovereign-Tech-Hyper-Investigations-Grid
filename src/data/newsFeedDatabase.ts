function buildTypedList(tuples: CompactNewsTuple[], type: NewsFeedItem['type'], prefix: string): NewsFeedItem[] {
  return tuples.map((t, idx) => ({
    id: `${prefix}-${String(idx + 1).padStart(2, '0')}`,
    type,
    title: t.title,
    entityName: t.entityName,
    secondaryEntity: t.secondaryEntity,
    domain: t.domain,
    date: t.date,
    timestamp: Date.now() - idx * 1000 * 60 * 45,
    jurisdiction: t.jurisdiction,
    details: t.details,
    price: t.price,
    source: t.source,
    reliabilityScore: t.reliabilityScore,
    impact: t.impact
  }));
}

